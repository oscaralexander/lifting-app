    <h2>Inleiding</h2>
    <p>
        Lifting Inspections B.V. is in het bezit van een EN ISO/IEC 17020:2012, type A accreditatie, van de Raad voor Accreditatie (RvA) met
        registratienummer I385 en is door de Minister van Sociale Zaken en Werkgelegenheid (SZW) aangewezen als NL-
        conformiteitsbeoordelingsinstantie (NL-CBI) die is bevoegd voor het uitvoeren van periodieke keuringen van hijskranen, zoals
        beschreven in het Warenwetbesluit machines, artikel 6d, 6ea en 6f en de Warenwetregeling machines, artikel 2.
        Aanwijzingsbeschikking Ministerie SZW: 2025-0000267580.
    </p>
    <h3>Nederlandse wetgeving</h3>
    <p>
        Hijskranen die behoren tot een bij ministeriële regeling omschreven categorie moeten conform het Warenwetbesluit machines gekeurd worden door een door de minister aangewezen instelling.<br>
        Voor de eerste maal dient dit te geschieden na verloop van ten hoogste 24 maanden na de eerste ingebruikneming en vervolgens telkens na verloop van ten hoogste 24 maanden.<br>
        (Warenwetbesluit machines artikel 6d). Voor de tussenliggende jaren dient overeenkomstig artikel 6d van het Warenwetbesluit machines de kraan te worden gekeurd door een deskundige natuurlijke persoon, rechtspersoon of instelling.</li>
    </p>
    <h3>TCVT</h3>
    <p>
        Het keuringsschema is opgesteld door de TCVT, identificatiecode: TCVT W3-01: 2025 (24-V11). Dit betreft de verplichte tweejaarlijkse keuringen. Meer informatie is te vinden op: <a href="https://www.tcvt.nl">www.tcvt.nl</a>.
    </p>
    <h3>Periodieke keuring</h3>
    <p>
        Tijdens de periodieke keuring worden de veranderingen die tijdens het gebruik van de machine zijn ontstaan door slijtage, veroudering of door het uitvoeren van onderhoud en reparatie, geïnspecteerd en worden de veiligheidsvoorzieningen functioneel getest. De periodieke keuring behelst de staat van de machine op het moment van keuren. De periodieke keuring vindt plaats zonder demontage van delen van de machine. Er wordt ook nagegaan of er een EG-verklaring van overeenstemming aanwezig is van de hijskraan.
    </p>
    <h3>Resultaat keuring</h3>
    <p>
        Tijdens de periodieke keuring kan er een categorie A- of een categorie B-tekortkoming waargenomen worden.
    </p>
    <h4>Geen tekortkomingen</h4>
    <ul>
        <li>Afgifte TCVT Certificaat van Goedkeuring gedateerd op de keuringsdatum, met de TCVT Goedkeuringssticker.</li>
    </ul>
    <h4>Categorie A-tekortkoming</h4>
    <ul>
        <li>Een tekortkoming met een direct gevaar voor elektrocutie, gevaar voor omvallen van de machine, gevaar voor bezwijken van dragende delen van de machine of voor het ongewild omlaag komen van de last.</li>
        <li>Er is een directe voorziening aan de machine noodzakelijk en gebruik van de machine is uit veiligheidsoogpunt dan ook onverantwoord en de machine moet buiten gebruik worden gesteld.</li>
        <li>
            De opdrachtgever geeft Lifting Inspections B.V. zo spoedig mogelijk, doch uiterlijk binnen 2 maanden na de keuring
            opdracht voor een nacontrole op de uitgevoerde reparaties.
            Lifting Inspections B.V. voert de nacontrole uit, tenzij de aard van de tekortkoming een schriftelijke of digitale afhandeling
            rechtvaardigt (<a href="mailto:afmelden@liftinginspections.nl">afmelden@liftinginspections.nl</a>)
        </li>
        <li>
            Als de afmelding niet binnen de gestelde termijn is geschied, dan mag geen certificaat worden afgegeven. In dat geval volgt
            altijd een volledige nieuwe keuring indien de opdrachtgever de machine in gebruik wil nemen. Indien de reparaties als
            adequaat worden gekwalificeerd, verstrekt Lifting Inspections B.V. aan de opdrachtgever het TCVT Certificaat van Goedkeuring.
        </li>
    </ul>
